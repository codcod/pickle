// ticketBody renders a minimal, parseable ticket file. hist is the full History
// bullet list (one line per entry, already "- YYYY-MM-DD — ..." formatted).
func ticketBody(id, title, impact, hist string) string {
	return fmt.Sprintf(`---
id: %s
title: %s
project: demo
depends-on: []
spawned-by: []
impact: %s
complexity: medium
cost: M
---

# %s — %s

## History

%s
`, id, title, impact, id, title, hist)
}

// mkTicket writes a ticket file into root/tickets/<dir>/.
func mkTicket(t *testing.T, root, dir, id, slug, body string) {
	t.Helper()
	p := filepath.Join(root, "tickets", dir, id+"-"+slug+".md")
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(body), 0o644); err != nil {
		t.Fatal(err)
	}
}

func loadTree(t *testing.T, root string) []*ticket.Ticket {
	t.Helper()
	tickets, issues := ticket.LoadAll(root)
	if len(issues) > 0 {
		t.Fatalf("load issues: %v", issues)
	}
	return tickets
}

